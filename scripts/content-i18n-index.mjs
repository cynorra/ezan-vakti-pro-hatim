// Regenerates lib/data/content-i18n/index.ts from the <lang>.json packs present, so a
// language whose translation failed is simply absent (English fallback) instead of
// breaking the bundle. Run after scripts/content-translate.mjs.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve('lib/data/content-i18n');
const langs = fs
  .readdirSync(dir)
  .filter((f) => /^[a-z]{2}\.json$/.test(f))
  .map((f) => f.slice(0, 2))
  .sort();

const ident = (lang) => `pack_${lang}`;
const out = `// Generated by scripts/content-i18n-index.mjs — do not edit by hand.
// Machine-translated (Gemini, validated) religious content for app languages other
// than tr/en/id/ms; see scripts/content-translate.mjs.

${langs.map((l) => `import ${ident(l)} from './${l}.json';`).join('\n')}

interface Text {
  title: string;
  meaning: string;
  source: string;
}

export interface ContentPack {
  duas: Record<string, Text>;
  wisdom: Record<string, { content: string; source: string }>;
  verses: Record<string, { content: string; source: string }>;
  /** 99 meanings, index = Esma.id - 1 */
  esma: string[];
}

export const contentPacks: Record<string, ContentPack> = {
${langs.map((l) => `  ${l}: ${ident(l)},`).join('\n')}
};
`;
fs.writeFileSync(path.join(dir, 'index.ts'), out);
console.log(`content-i18n/index.ts: ${langs.length} languages (${langs.join(', ')})`);
